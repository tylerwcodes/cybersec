    ("Document findings", "Step 7 (final): record findings, actions, outcomes, and lessons learned in the ticket/knowledge base; notes are taken throughout the process"),
    ("Question users", "Step 1 activity: interview those reporting the issue with open-ended then closed questions to translate complaints into technical symptoms"),
    ("Question the obvious", "Step 2 habit: check simple likely causes first (unplugged cable, disabled port, wrong SSID) before exotic theories"),
    ("Determine if anything has changed", "Step 1 activity: check change logs and ask about recent modifications; recent change is the most common root cause"),
