    ("Approach multiple problems individually", "Step 1 principle: split simultaneously reported issues into separate problems and troubleshoot each independently"),
    ("Top-to-bottom approach", "Theory-building method that starts at OSI Layer 7 (application) and works down; suits application-specific symptoms"),
