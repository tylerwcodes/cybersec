    ("Policy", "High-level, mandatory statement of management intent and expectations; technology-neutral and slow to change — the 'why/what' layer of governance"),
    ("Standard", "Mandatory, specific, measurable requirements that implement policy — e.g., minimum password length, approved encryption algorithms"),
    ("Procedure", "Mandatory step-by-step instructions for performing a task consistently — the 'how' layer of governance"),
    ("Guideline", "Recommended best practices and advice; the only NON-mandatory governance document type — flexible where judgment is acceptable"),
    ("Acceptable use policy (AUP)", "Policy defining what users may and may not do with organizational systems, networks, and data; typically signed during onboarding"),
    ("Information security policies", "The overarching set of management-approved rules protecting the confidentiality, integrity, and availability of information"),
    ("Business continuity (BC) policy", "Policy for keeping critical business operations running during and after a disruption — the broader discipline that contains DR"),
    ("Disaster recovery (DR) policy", "IT-focused subset of business continuity: restoring systems and data after a disaster — backups, recovery sites, RTO/RPO targets"),
    ("Incident response policy", "Policy defining how the organization prepares for, detects, reports, and responds to security incidents, including team roles and escalation"),
    ("SDLC policy", "Software development lifecycle policy — builds security into every development phase: requirements, design, coding, testing, deployment, maintenance"),
    ("Change management policy", "Policy requiring changes to systems to follow a formal request/approval/testing process so changes don't cause outages or vulnerabilities"),
    ("Password standard", "Mandatory password construction/handling requirements: minimum length, screening or complexity, history, lockout, hashed-and-salted storage"),
    ("Access control standard", "Mandatory requirements for granting, reviewing, and revoking access: least privilege, need-to-know, role-based assignment, periodic reviews"),
    ("Physical security standard", "Mandatory physical-protection requirements: badges, visitor handling, locks, access-control vestibules, camera coverage, server-room rules"),
    ("Encryption standard", "Mandatory list of approved algorithms, key lengths, and protocol versions (e.g., AES-256 at rest, TLS 1.2+ in transit) plus key management"),
    ("Change management procedure", "Ordered steps for a change: request, risk assessment/approval (often via CAB), scheduled window, implement with backout plan, verify, document"),
    ("Onboarding procedure", "Steps for bringing in a new hire: background screening, signing the AUP/NDA, least-privilege account provisioning, equipment, security training"),
    ("Offboarding procedure", "Steps for departure: promptly disable accounts and revoke access, recover assets, exit interview/NDA reminder; failures leave stale accounts"),
    ("Playbook", "Checklist-style, step-by-step response guide for one specific scenario or incident type (e.g., phishing); often automated via SOAR"),
    ("Regulatory consideration", "External governance driver: rules imposed and enforced by government regulators (e.g., HIPAA, SOX, GLBA) with fines for non-compliance"),
    ("Legal consideration", "External driver from the broader legal system: breach-notification duties, e-discovery/legal hold, contracts, liability, due care/due diligence"),
    ("Industry consideration", "Sector-specific requirements, including contractual standards that are not laws — PCI DSS for payment cards is the classic example"),
