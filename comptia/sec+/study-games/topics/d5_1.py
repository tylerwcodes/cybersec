    ("Government entities", "Legislatures, regulators, and agencies acting as external governance by creating and enforcing law; the governing structure for the public sector"),
    ("Centralized governance", "A single central authority makes security decisions for the whole organization — consistent and uniform, but slower and less locally tailored"),
    ("Decentralized governance", "Decision authority distributed to business units or regions — faster and flexible, but risks inconsistent controls between units"),
