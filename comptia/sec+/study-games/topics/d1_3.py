TERMS = [
    ("Change management", "Formal process for requesting, approving, testing, implementing, and documenting changes so they do not introduce security risks or unplanned outages"),
    ("Approval process", "Formal review and sign-off (often by a change advisory board) required before a change can be implemented; prevents unauthorized or risky changes"),
    ("Change advisory board (CAB)", "Group of stakeholders that reviews change requests, weighs risk and impact, and approves, denies, or reschedules them"),
    ("Ownership", "Assignment of a specific person or team responsible for a change or the asset being changed; the owner drives the change and is accountable for its outcome"),
    ("Stakeholders", "Individuals or departments affected by a change who must be identified and consulted so the change does not disrupt their operations"),
    ("Impact analysis", "Assessment performed before a change to determine what systems, users, and business processes could be affected and how severe the effect could be"),
    ("Test results", "Evidence from trying the change in a sandbox/test environment first; reviewed during approval to confirm the change works and is safe to deploy"),
    ("Backout plan", "Documented procedure to reverse a change and restore the previous known-good state if the change fails or causes problems"),
    ("Maintenance window", "Scheduled block of time, usually during off-peak hours, when changes may be implemented so any downtime has minimal business impact"),
    ("Standard operating procedure (SOP)", "Step-by-step documented instructions for performing a routine task the same way every time, including how changes must be submitted and handled"),
    ("Emergency change", "Change implemented outside the normal schedule to fix an urgent security or availability issue; still documented and reviewed, often retroactively"),
    ("Allow list (whitelist)", "Security control that permits only explicitly listed applications or entities and blocks everything else; must be updated when a change adds new software"),
    ("Deny list (blocklist)", "Security control that blocks explicitly listed applications or entities and permits everything else; changes may require adding or removing entries"),
    ("Restricted activities", "Actions the change approval explicitly does NOT authorize; technicians may only perform the work within the defined scope of the approved change"),
    ("Downtime", "Period when a system or service is unavailable; changes should be scheduled in maintenance windows and communicated to minimize its impact"),
    ("Service restart", "Stopping and starting an OS service/daemon so a configuration change takes effect; causes a brief interruption for users of that service"),
    ("Application restart", "Closing and relaunching an application so it loads changed settings or patched files; sessions or unsaved work in the app may be lost"),
    ("System reboot", "Full restart of the operating system, required by some patches and kernel/driver changes; produces longer downtime than a service restart"),
    ("Legacy applications", "Older software that is no longer supported or updated by the vendor; fragile under change and often requires special testing and compensating controls"),
    ("Dependencies", "Other systems, services, or libraries that must be present or modified for a change to work; a change to one component can break the components that rely on it"),
    ("Updating diagrams", "Post-change documentation task of revising network and architecture diagrams so they accurately reflect the current environment"),
    ("Updating policies/procedures", "Post-change documentation task of revising written policies and procedures affected by the change so staff follow the new correct steps"),
    ("Version control", "System that tracks changes to files/configurations over time, showing who changed what and when, and allowing rollback to earlier versions"),
    ("Change request", "Formal submission describing a proposed change, its purpose, scope, risk, schedule, and backout plan; the starting point of the change process"),
]

