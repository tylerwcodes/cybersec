    ("Ransomware", "Malware that encrypts a victim's files and demands payment for the decryption key; indicators include renamed/encrypted files and ransom notes"),
    ("Trojan", "Malware disguised as a legitimate program; delivers a hidden payload such as a backdoor when the user installs or runs it"),
    ("Worm", "Self-replicating malware that spreads across networks without user interaction or a host file; indicators include traffic spikes and mass scanning"),
    ("Virus", "Malware that attaches to a host file or program and requires the user to execute it before it can run and replicate"),
    ("Spyware", "Malware that covertly monitors user activity, browsing habits, and data without the user's knowledge or consent"),
    ("Bloatware", "Unwanted preinstalled software that consumes resources and expands the attack surface; unwanted but not inherently malicious"),
    ("Keylogger", "Software or hardware that records every keystroke to capture credentials, messages, and other sensitive input"),
    ("Logic bomb", "Malicious code that lies dormant until triggered by a specific condition such as a date, time, or event (e.g., an account being disabled)"),
    ("Rootkit", "Malware embedded in the OS or kernel that conceals its own presence; often detectable only by scanning from trusted boot media"),
    ("RFID cloning", "Copying the data from a proximity badge or tag onto a duplicate so an attacker can impersonate the legitimate holder"),
    ("Reflected DDoS", "DDoS technique where the attacker spoofs the victim's IP address in requests to third-party servers, whose replies flood the victim"),
    ("Amplified DDoS", "Reflected DDoS using protocols such as DNS or NTP where small spoofed queries generate much larger responses, multiplying attack traffic"),
    ("DNS poisoning", "Corrupting DNS caches or records so that domain names resolve to attacker-controlled IP addresses, silently redirecting users"),
    ("On-path attack", "Attacker secretly positioned between two communicating parties (e.g., via ARP poisoning) to intercept or alter traffic; formerly 'man-in-the-middle'"),
    ("Credential replay", "Reusing captured authentication material — such as a password hash (pass-the-hash) or session token — to authenticate without cracking the password"),
    ("Injection attack", "Supplying crafted input (SQL, command, LDAP) that a vulnerable application passes to an interpreter and executes"),
    ("Buffer overflow", "Writing more data than a memory buffer can hold, corrupting adjacent memory to crash the application or execute attacker code"),
    ("Privilege escalation", "Exploiting a flaw or misconfiguration to gain rights beyond those assigned, such as moving from standard user to administrator/root"),
    ("Forgery (CSRF)", "Cross-site request forgery: tricks an authenticated user's browser into submitting unwanted requests to a web application that trusts that user"),
    ("Directory traversal", "Using ../ sequences in input to escape the web root and access unauthorized files such as /etc/passwd"),
    ("Downgrade attack", "Forcing two parties to negotiate an older, weaker protocol version or cipher so the attacker can break the weaker protection"),
    ("Collision attack", "Finding two different inputs that produce the same hash digest, undermining the integrity guarantees of the hash function"),
    ("Birthday attack", "Uses birthday-paradox probability to find hash collisions far faster than naive brute force; the reason longer hash outputs are required"),
    ("Password spraying", "Trying one or a few common passwords against many different accounts, staying under lockout thresholds to avoid detection"),
    ("Impossible travel", "Account indicator: successive logins from locations too far apart to physically travel between in the elapsed time"),
    ("Out-of-cycle logging", "Indicator: log events (updates, jobs, reboots) recorded at unexpected times outside the normal schedule, suggesting attacker activity"),
